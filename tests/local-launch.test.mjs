import assert from 'node:assert/strict';
import { test } from 'node:test';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import net from 'node:net';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { fileURLToPath } from 'node:url';

const exec = promisify(execFile);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
test('local launcher starts a zero-role company once and stops without removing saved settings', async (t) => {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'one-company-launch-'));
  const reservation = net.createServer();
  await new Promise((resolve) => reservation.listen(0, '127.0.0.1', resolve));
  const port = reservation.address().port; await new Promise((resolve) => reservation.close(resolve));
  const env = { ...process.env, PORT: String(port), YEWANG_DATA_DIR: path.join(tmp, 'data'), YEWANG_RUNTIME_DIR: path.join(tmp, 'runtime'), CODEX_HOME: path.join(tmp, 'empty-codex'), YEWANG_IMPORT_COMPANY: '0', ONE_PERSON_COMPANY_NO_OPEN: '1' };
  let started;
  const manage = async (command) => JSON.parse((await exec(process.execPath, [path.join(root, 'scripts/manage.mjs'), command, '--json'], { cwd: root, env, timeout: 15000 })).stdout);
  t.after(async () => { try { await manage('stop'); } catch { if (started?.pid) try { process.kill(started.pid, 'SIGTERM'); } catch { /* exited */ } } fs.rmSync(tmp, { recursive: true, force: true }); });
  started = await manage('start'); assert.equal(started.running, true); assert.equal(started.reused, false);
  const base = `http://127.0.0.1:${port}`;
  const get = async (route) => (await fetch(base + route)).json();
  assert.equal((await get('/api/setup')).required, true);
  assert.equal((await get('/api/setup')).name, '我的公司');
  assert.deepEqual((await get('/api/roles')).roles, []);
  assert.deepEqual((await get('/api/sessions')).sessions, []);
  assert.deepEqual((await get('/api/runs')).runs, []);
  assert.equal((await get('/api/runtime')).status, 'stopped');
  assert.equal((await get('/api/desktop-manager')).configured, false);
  const again = await manage('start'); assert.equal(again.reused, true); assert.equal(again.pid, started.pid);
  await fetch(base + '/api/setup', { method: 'PATCH', headers: { 'content-type': 'application/json', 'x-yewang-workbench': '1' }, body: JSON.stringify({ name: '保留我的公司' }) });
  assert.equal((await manage('stop')).stopped, true);
  assert.equal(JSON.parse(fs.readFileSync(path.join(tmp, 'data/state.json'))).workspace.name, '保留我的公司');
  assert.equal((await manage('status')).running, false);
  started = await manage('start');
  assert.equal((await get('/api/setup')).name, '保留我的公司');
});
